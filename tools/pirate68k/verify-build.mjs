import {post,call,type,shot,waitFor,record,state} from './verify-lib.mjs';
const system=process.argv[2];
if(!system)throw new Error('Usage: node verify-build.mjs <HUMAN302.XDF>');
await post('open',{url:'http://127.0.0.1:5299/?bridge=3199&system=1&run=1&cpu=16&ram=2'});
await post('insert',{slot:'fdd0',path:system,name:'HUMAN302.XDF'});
await post('insert',{slot:'fdd1',path:'_local/pirate68k/dev.xdf',name:'dev.xdf'});
await call('reset');
const boot=await waitFor(async()=>{const r=await call('screen_text');return r.lines?.some(l=>l.includes('Command version'))&&r;},45000);
if(!boot.lines.some(l=>l.includes('version 3.02')))throw new Error('Human68k 3.02 not observed');
await record('boot',boot);await shot('human68k');
await record('connected',await call('status'));
const listing={};
for(const path of ['/','/BIN','/SRC','/OUT'])listing[path]=await call('disk_list_files',{slot:'fdd1',path});
await record('development-listing',listing);
await type('B:\\BUILD\n');
const build=await waitFor(async()=>{const r=await call('screen_text');if(r.lines.some(l=>l.includes('BUILD FAILED')))throw new Error('Guest build failed');return r.lines.some(l=>l.includes('BUILD OK:'))&&r;},45000);
await record('guest-build',build);await shot('guest-build');
const files=await call('disk_list_files',{slot:'fdd1',path:'/OUT'});
const executable=files.entries.find(e=>e.name.toUpperCase()==='PIRATE.X');
if(!executable||executable.size<131072)throw new Error('Linked executable missing');
await record('executable',executable);
await post('get',{slot:'fdd1',path:'/OUT/PIRATE.X',name:'PIRATE.X'});
console.log(JSON.stringify({result:'PASS',executable}));
await type('B:\\OUT\\PIRATE\n');
await waitFor(async()=>{const r=await call('status');return r.screen.width===256&&r.screen.height===256;});
await waitFor(async()=>{const s=await state();return s.mode===0&&s;});
await call('wait_screen_change',{stable_ms:500,timeout_ms:5000});
await shot('title');
console.log('Title launched in 256x256 mode');
